let current = "ru";

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = STRINGS[lang] ? lang : "en";
  return current;
}

/** Язык по локали Photoshop ("ru_RU" → "ru"), иначе английский. */
export function langFromLocale(locale) {
  return /^ru/i.test(String(locale || "")) ? "ru" : "en";
}

export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(STRINGS[current], key);
}

export function t(key, vars) {
  const text = STRINGS[current][key] !== undefined ? STRINGS[current][key] : STRINGS.en[key];
  if (text === undefined) return key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
}

/** Подставляет строки во все элементы с атрибутом data-i18n. */
export function applyI18n(root) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  root.documentElement && root.documentElement.setAttribute("lang", current);
}
